def names():
    return list(BREEDS)


def folder_map():
    return {b["folder"]: name for name, b in BREEDS.items()}


def appearance_of(name):
    return dict(BREEDS[name]["appearance"]) if name in BREEDS else None


def build_of(name):
    return BREEDS[name]["build"] if name in BREEDS else None


def markings_of(name):
    return dict(BREEDS[name].get("markings", {})) if name in BREEDS else None


def colours_of(name):
    return dict(BREEDS[name]["colours"]) if name in BREEDS else None


def fold_map():
    return {name: list(b["fold"]) for name, b in BREEDS.items()}


def resolve(text):
    if not text:
        return None
    t = text.lower().replace("_", " ").replace("-", " ").strip()

    if t in (n.lower() for n in BREEDS):
        return next(n for n in BREEDS if n.lower() == t)

    for name, b in BREEDS.items():
        for a in b["aliases"]:
            a = a.lower()
            if a in t or t in a:
                return name

    for name, b in BREEDS.items():
        for k in b["fold"]:
            if k.lower().replace("_", " ") in t:
                return name
    return None


def validate(verbose=True):
    required_app = {"ear_type", "ear_len", "ear_width", "tail_len",
                    "tail_curl", "tail_set", "muzzle_len", "coat"}
    required_col = {"base", "dark", "light"}
    problems = []
    for name, b in BREEDS.items():
        for key in ("folder", "aliases", "fold", "build", "appearance", "colours"):
            if key not in b:
                problems.append(f"{name}: missing '{key}'")
        missing = required_app - set(b.get("appearance", {}))
        if missing:
            problems.append(f"{name}: appearance missing {sorted(missing)}")
        missing = required_col - set(b.get("colours", {}))
        if missing:
            problems.append(f"{name}: colours missing {sorted(missing)}")
        if b["appearance"]["ear_type"] not in ("floppy", "semi_erect", "erect"):
            problems.append(f"{name}: bad ear_type {b['appearance']['ear_type']}")
        for part, role in b.get("markings", {}).items():
            if role not in ("base", "dark", "light"):
                problems.append(f"{name}: marking '{part}' has bad role '{role}'")
        if resolve(name) != name:
            problems.append(f"{name}: does not resolve to itself -- check aliases")

    if verbose:
        if problems:
            print(f"{len(problems)} problem(s):")
            for p in problems:
                print("  -", p)
        else:
            print(f"All {len(BREEDS)} breed entries are complete and self-resolving.")
    return problems


